/* The left content edge of block container `cb` in the frame of context root `root`: §9.4.1's horizontal rule
   applied down the chain of containing blocks, which in one block formatting context is the chain of in-flow
   block containers. CSS 2.2 §9.4.3's relative translation moves no box of this frame ("Offsetting a box (B1) in
   this way has no effect on the box (B2) that follows"), so none is added. */
static CssPx get_content_left(lxb_dom_element_t *cb, lxb_dom_element_t *root)
{
    CssPx left = css_px(0.0);
    lxb_dom_element_t *x;
    char xbuf[160], rbuf[160];

    for (x = cb; x != root; x = used_value_containing_block(x)) {
        DCHECKF(x != NULL && block_flow_context_root(x) == root,
                "%s: the chain of containing blocks from a float's containing block left its block formatting "
                "context before reaching the context root %s",
                x != NULL ? box_subject(x, xbuf, sizeof xbuf) : "(none)", box_subject(root, rbuf, sizeof rbuf));
        left = css_px_add(left, css_px_add(flow_block_inline_offset(x), used_value_leading_edge_px(x, false)));
    }
    return left;
}

/* Whether the placed margin box `o` shares a vertical position with the band `[y, y + h)` a float of height `h`
   would take. A float of zero height occupies the line `y` alone, which a box spanning it still shares. */
static bool get_overlaps(const FlowFloatBox *o, CssPx y, CssPx h)
{
    double bottom = o->top.px + o->height.px;

    return bottom > y.px && (o->top.px < y.px + h.px || o->top.px <= y.px);
}

/* §9.5.1's placement of float `f`, given every earlier float of its context placed (`prev`, `n` of them). */
static bool get_place(lxb_dom_element_t *f, lxb_dom_element_t *root, lxb_dom_element_t *const *prev, size_t n,
                      FlowFloatBox *out)
{
    lxb_dom_element_t *cb = block_flow_static_position_containing_block(f);
    CssPx start, frame_top, cb_left, cb_right, y, w, h, ignored;
    FlowFloatBox *placed;
    size_t i;
    char fbuf[160], cbuf[160];

    /* The margin box's size: §10.3.5's shrink-to-fit width and §10.6.7's height, measured first where they
       read the float's content so a resting drive can stop there. */
    if (css_computed_length_is(f, "width", CSS_KEYWORD_AUTO) && !intrinsic_inline_sizes_ask(f)) return false;
    if (block_flow_display_is_block_container(css_computed_display(f)) && used_value_height_behaves_as_auto(f) &&
        !block_flow_auto_height_ask(f, &ignored))
        return false;
    /* "A floating box's outer top may not be higher than the top of its containing block. When the float occurs
       between two collapsing margins, the float is positioned as if it had an otherwise empty anonymous block
       parent taking part in the flow", which is where §9.4.1's stack stands at the float's place
       (`block_flow_float_top_ask`), and "the outer top of a floating box may not be higher than the outer top
       of any block or floated box generated by an element earlier in the source document", which that place
       already is for the block boxes. */
    if (!block_flow_float_top_ask(f, &start)) return false;
    if (!flow_placement_bfc_frame_peek(cb, &frame_top))
        DFAILF("%s, in %s: the walk of this float's containing block answered the float's place and recorded no "
               "top content edge in its formatting context; every walk with a placement record held writes one",
               box_subject(f, fbuf, sizeof fbuf), box_subject(cb, cbuf, sizeof cbuf));
    y = css_px_add(frame_top, start);
    cb_left = get_content_left(cb, root);
    cb_right = css_px_add(cb_left, used_value_containing_block_width(f));
    w = css_px_add(used_value_border_edge_px(f, false),
                   css_px_add(used_value_px(f, "margin-left"), used_value_px(f, "margin-right")));
    h = css_px_add(used_value_border_edge_px(f, true),
                   css_px_add(used_value_px(f, "margin-top"), used_value_px(f, "margin-bottom")));
    out->width = w;
    out->height = h;
    out->right = block_flow_float_is_right(f);
    placed = malloc((n != 0 ? n : 1) * sizeof *placed);
    CHECK(placed != NULL, "out of memory placing one float");
    for (i = 0; i < n; i++)
        if (!flow_placement_float_box_peek(prev[i], &placed[i]))
            DFAILF("%s: an earlier float of its context was not placed before it", box_subject(f, fbuf, sizeof fbuf));
    /* "The outer top of a floating box may not be higher than the outer top of any ... floated box generated by
       an element earlier in the source document." Earlier floats' tops never decrease, so the last is the
       highest of them. */
    if (n > 0) y = css_px_max(y, placed[n - 1].top);
    for (;;) {
        CssPx left = cb_left, right = cb_right, next = css_px(0.0);
        bool any = false;

        /* The edges the floats beside the band leave: "for each such earlier box, either the left outer edge of
           the current box must be to the right of the right outer edge of the earlier box, or its top must be
           lower than the bottom of the earlier box", and "the right outer edge of a left-floating box may not be
           to the right of the left outer edge of any right-floating box that is next to it". */
        for (i = 0; i < n; i++) {
            CssPx bottom = css_px_add(placed[i].top, placed[i].height);

            if (!get_overlaps(&placed[i], y, h)) continue;
            if (placed[i].right) right = css_px_min(right, placed[i].left);
            else left = css_px_max(left, css_px_add(placed[i].left, placed[i].width));
            next = any ? css_px_min(next, bottom) : bottom;
            any = true;
        }
        /* "A floating box must be placed as high as possible": it stays at `y` if it fits between those edges,
           and with no float beside it at all it stays whatever its width ("a left float may not stick out at the
           right edge, unless it is already as far to the left as possible"). Otherwise it moves down to the
           nearest bottom among the floats beside it, which is below `y`. */
        if (!any || left.px + w.px <= right.px) {
            out->top = y;
            out->left = out->right ? css_px_sub(right, w) : left;
            break;
        }
        y = next;
    }
    free(placed);
    return true;
}

bool float_placement_ask(lxb_dom_element_t *f, FlowFloatBox *out)
{
    lxb_dom_node_t *parent;
    lxb_dom_element_t *root, **v;
    size_t n, i, k;
    char fbuf[160];

    DCHECKF(f != NULL && block_flow_is_floated(f), "%s: §9.5.1's placement was asked of a box that does not float",
            f != NULL ? box_subject(f, fbuf, sizeof fbuf) : "(no element)");
    DCHECK(flow_placement_is_held(), "§9.5.1's placement was asked with no placement record held; the walks it "
                                     "reads record their frames only there");
    if (flow_placement_float_box_peek(f, out)) return true;
    parent = lxb_dom_interface_node(f)->parent;
    DCHECKF(parent != NULL && parent->type == LXB_DOM_NODE_TYPE_ELEMENT, "%s floats with no element parent",
            box_subject(f, fbuf, sizeof fbuf));
    root = block_flow_context_root(lxb_dom_interface_element(parent));
    if (!block_flow_context_floats_ask(lxb_dom_interface_element(parent), &v, &n)) return false;
    for (k = 0; k < n && v[k] != f; k++) {}
    DCHECKF(k < n, "%s floats and is not among its context's floats", box_subject(f, fbuf, sizeof fbuf));
    /* Document order, each against those before it; a placement already recorded stays. */
    for (i = 0; i <= k; i++) {
        FlowFloatBox b;

        if (flow_placement_float_box_peek(v[i], &b)) continue;
        if (!get_place(v[i], root, v, i, &b)) {
            free(v);
            return false;
        }
        flow_placement_float_box_record(v[i], b);
    }
    free(v);
    if (!flow_placement_float_box_peek(f, out))
        CHECK_FAIL("a float placement was not readable back from the placement record that holds it");
    return true;
}
