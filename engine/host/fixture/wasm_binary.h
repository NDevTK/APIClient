#define ENGINE_HOST_FIXTURE_WASM_BINARY_H

#include <stddef.h>

#define WB_END "unexpected end"
#define WB_MAGIC "magic header not detected"
#define WB_VERSION "unknown binary version"
#define WB_ID "malformed section id"
#define WB_ORDER "unexpected content after last section"
#define WB_LONG "integer representation too long"
#define WB_LARGE "integer too large"
#define WB_BOUNDS "length out of bounds"
#define WB_UTF8 "malformed UTF-8 encoding"
#define WB_SIZE "section size mismatch"
#define WB_MUT "malformed mutability"
#define WB_REF "malformed reference type"
#define WB_HEAP "malformed heap type"
#define WB_STORAGE "malformed storage type"
#define WB_COMP "malformed definition type"
#define WB_KIND "malformed import kind"
#define WB_LIMITS "malformed limits flags"
#define WB_ZERO "zero byte expected"

typedef struct {
    const char *src;
    size_t len;
    const char *expect;
    const char *bytes;
} WasmBinaryRow;

/* One section as module_decoder.h's WasmSection states it: id, offset, size, name offset, name size. */
typedef struct {
    unsigned id;
    size_t offset, size, name_offset, name_size;
} WasmBinarySection;

typedef struct {
    const char *src;
    size_t len;
    size_t n_sections;
    const char *bytes;
    WasmBinarySection sections[32];
} WasmBinaryDetail;

/* A module and its sections as test_forced.c renders them (wasm_type_text, wasm_import_text, wasm_func_text,
   wasm_code_text, wasm_segment_text). */
typedef struct {
    const char *src;
    size_t len;
    const char *bytes;
    const char *text;
} WasmTextRow;

