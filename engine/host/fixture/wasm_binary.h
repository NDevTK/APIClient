typedef struct {
    const char *src;
    size_t len;
    const char *expect;
    const char *bytes;
} WasmBinaryRow;

/* One section as module_decoder.h's WasmSection states it: id, offset, size, name offset, name size. */
typedef struct {
    unsigned id;
    size_t offset, size, name_offset, name_size;
} WasmBinarySection;

typedef struct {
    const char *src;
    size_t len;
    size_t n_sections;
    const char *bytes;
    WasmBinarySection sections[32];
} WasmBinaryDetail;

/* A module and one of its sections as test_forced.c renders it (wasm_type_text, wasm_import_text,
   wasm_func_text, wasm_code_text). */
typedef struct {
    const char *src;
    size_t len;
    const char *bytes;
    const char *text;
} WasmTextRow;

