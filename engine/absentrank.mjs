const ncAll = (n) => [...(notcode.get(n) || new Map()).values()].reduce((a, b) => a + b, 0);
let refFiles = 0, refRefused = 0, refTick = 0, refMigrated = 0, refBytes = 0;
let refBindAsked = 0, refBindRefused = 0;
const refWhy = new Map(), refExcluded = [];
